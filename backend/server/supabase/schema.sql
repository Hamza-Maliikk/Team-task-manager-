-- The API uses the Supabase client; this file only creates the required tables.

CREATE TABLE IF NOT EXISTS public.users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(100)  NOT NULL,
  email         VARCHAR(255)  NOT NULL UNIQUE,
  password_hash TEXT          NOT NULL,
  created_at    TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.teams (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(100) NOT NULL,
  owner_id   BIGINT       NOT NULL CONSTRAINT teams_owner_id_fkey REFERENCES public.users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.team_members (
  team_id BIGINT NOT NULL CONSTRAINT team_members_team_id_fkey REFERENCES public.teams(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL CONSTRAINT team_members_user_id_fkey REFERENCES public.users(id) ON DELETE CASCADE,
  role    VARCHAR(10) NOT NULL DEFAULT 'member' CHECK (role IN ('owner', 'member')),
  PRIMARY KEY (team_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.tasks (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       VARCHAR(200) NOT NULL,
  description TEXT         NOT NULL DEFAULT '',
  status      VARCHAR(12)  NOT NULL DEFAULT 'todo' CHECK (status IN ('todo', 'in_progress', 'done')),
  priority    VARCHAR(6)   NOT NULL DEFAULT 'medium' CHECK (priority IN ('low', 'medium', 'high')),
  due_date    DATE,
  team_id     BIGINT NOT NULL CONSTRAINT tasks_team_id_fkey REFERENCES public.teams(id) ON DELETE CASCADE,
  assignee_id BIGINT CONSTRAINT tasks_assignee_id_fkey REFERENCES public.users(id) ON DELETE SET NULL,
  created_by  BIGINT CONSTRAINT tasks_created_by_fkey REFERENCES public.users(id) ON DELETE SET NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_tasks_team ON public.tasks(team_id);
CREATE INDEX IF NOT EXISTS idx_tasks_assignee ON public.tasks(assignee_id);

CREATE TABLE IF NOT EXISTS public.sessions (
  sid    TEXT PRIMARY KEY,
  sess   JSONB       NOT NULL,
  expire TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_sessions_expire ON public.sessions(expire);

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
